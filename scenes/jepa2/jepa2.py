CEM_EQS=[r'a_{1:H}^{(i)} \sim \mathcal{N}(\mu, \sigma^{2})',
         r'\hat{z}_{t+H}^{(i)} = P_{\phi}(z_t, a_{1:H}^{(i)})',
         r'E^{(i)} = \lVert \hat{z}_{t+H}^{(i)} - z_g \rVert_1',
         r'\mu, \sigma \leftarrow \mathrm{fit}(\mathrm{top}\text{-}k)']


def frame_patches(t, n=4, size=1.5):
    """One video frame as an n x n grid of patches. A bright 'ball' moves left to right with t."""
    side=size/n
    grid=VGroup()
    ball=np.array([0.2+0.6*t, 0.55-0.15*t])
    for r in range(n):
        for c in range(n):
            center=np.array([(c+0.5)/n, 1-(r+0.5)/n])
            v=np.exp(-np.sum((center-ball)**2)/0.04)
            sq=Square(side_length=side*0.94)
            sq.set_stroke(PANEL, 1)
            sq.set_fill(mix(PATCH_LOW, AMBER, v), 1.0)
            sq.move_to([(c-(n-1)/2)*side, ((n-1)/2-r)*side, 0])
            grid.add(sq)
    border=SurroundingRectangle(grid, buff=0.04).set_stroke(MUTED, 2)
    return VGroup(grid, border)


def embedding_row(colors, side=0.32):
    row=VGroup(*[Square(side_length=side).set_fill(c, 1).set_stroke(TEXT, 1.5) for c in colors])
    row.arrange(RIGHT, buff=0.06)
    return row


class JEPA2Overview(Scene):
    LANG='en'

    def construct(self):
        board=Storyboard(__file__, self.LANG)
        T=board.text
        rng=np.random.default_rng(3)

        # ---------------------------------------------------------------- Title
        board.start(self, 'intro')
        title=label('JEPA 2', font_size=110, weight='ULTRABOLD')
        subtitle=label(T['subtitle'], font_size=34, color=MUTED)
        subtitle.next_to(title, DOWN, buff=0.45)
        self.play(Write(title), run_time=1.5)
        self.play(FadeIn(subtitle, shift=0.2*UP), run_time=1.2)
        self.wait(1.2)
        board.hold(self, reserve=1.2)
        self.play(FadeOut(subtitle), title.animate.scale(0.38).to_corner(UL, buff=0.35), run_time=1.2)

        # ---------------------------------------------------------------- Part 1: masked latent prediction
        board.start(self, 'masked_prediction')
        section=label(T['section1'], font_size=30, color=MUTED)
        section.next_to(title, RIGHT, buff=0.5).align_to(title, DOWN)
        self.play(FadeIn(section), run_time=0.8)

        masked_ids=[5, 6, 9, 10]  # same spatial positions in every frame: a tube through time
        frames=VGroup(*[frame_patches(t) for t in (0.0, 0.5, 1.0)])
        for i, f in enumerate(frames):
            f.shift(i*np.array([0.35, -0.3, 0]))
        frames.move_to([-4.4, 0.0, 0])
        video_label=label(T['video'], font_size=26, color=MUTED).next_to(frames, DOWN, buff=0.3)

        self.play(LaggedStart(*[FadeIn(f, shift=0.2*RIGHT) for f in frames], lag_ratio=0.3),
                  FadeIn(video_label), run_time=2)

        tube=VGroup(*[f[0][i] for f in frames for i in masked_ids])
        self.play(*[sq.animate.set_fill(PANEL, 1).set_stroke(PINK, 2) for sq in tube], run_time=1.2)
        mask_label=label(T['mask'], font_size=24, color=PINK).next_to(frames, UP, buff=0.3)
        self.play(FadeIn(mask_label), run_time=0.6)

        context_enc=card('Encoder x', width=2.1, color=SKY).move_to([-1.0, -1.4, 0])
        target_enc=card('Encoder y (EMA)', width=2.7, color=SAND).move_to([-1.0, 1.6, 0])
        predictor=card('Predictor', width=2.0, color=AMBER).move_to([2.2, -1.4, 0])

        arrow_ctx=Arrow(frames.get_right()+0.2*DOWN, context_enc.get_left(), buff=0.15).set_color(TEXT)
        arrow_tgt=Arrow(frames.get_right()+0.2*UP, target_enc.get_left(), buff=0.15).set_color(TEXT)
        arrow_pred=Arrow(context_enc.get_right(), predictor.get_left(), buff=0.12).set_color(TEXT)

        self.play(GrowArrow(arrow_ctx), FadeIn(context_enc), run_time=1.0)
        self.play(GrowArrow(arrow_pred), FadeIn(predictor), run_time=1.0)

        target_colors=[mix(PATCH_LOW, AMBER, v) for v in rng.uniform(0.25, 1.0, 4)]
        pred_colors=[mix(c, PINK, 0.5) for c in target_colors]
        pred_row=embedding_row(pred_colors).next_to(predictor, RIGHT, buff=0.5)
        pred_label=eq_label(r'\hat{s}', T['predicted'], font_size=22).next_to(pred_row, DOWN, buff=0.2)
        arrow_out=Arrow(predictor.get_right(), pred_row.get_left(), buff=0.1).set_color(TEXT)
        self.play(GrowArrow(arrow_out),
                  LaggedStart(*[FadeIn(s, scale=0.5) for s in pred_row], lag_ratio=0.15),
                  FadeIn(pred_label), run_time=1.3)

        self.play(GrowArrow(arrow_tgt), FadeIn(target_enc), run_time=1.0)
        target_row=embedding_row(target_colors).match_x(pred_row).match_y(target_enc)
        target_label=eq_label(r's', T['target'], font_size=22).next_to(target_row, UP, buff=0.2)
        arrow_tgt_out=Arrow(target_enc.get_right(), target_row.get_left(), buff=0.1).set_color(TEXT)
        self.play(GrowArrow(arrow_tgt_out),
                  LaggedStart(*[FadeIn(s, scale=0.5) for s in target_row], lag_ratio=0.15),
                  FadeIn(target_label), run_time=1.3)

        loss=eq(r'\mathcal{L} = \lVert \hat{s} - \mathrm{sg}(s) \rVert_1', font_size=40, color=AMBER)
        loss.move_to(VGroup(pred_row, target_row)).shift(0.15*UP)
        loss_box=SurroundingRectangle(loss, buff=0.2).set_stroke(AMBER, 2).set_fill(PANEL, 1)
        self.play(FadeIn(loss_box), Write(loss), run_time=1.4)

        # Training: predictions drift toward the targets
        new_pred=embedding_row(target_colors).move_to(pred_row)
        self.play(Transform(pred_row, new_pred), run_time=1.6)
        no_pixels=label(T['no_pixels'], font_size=26, color=EMERALD).to_edge(DOWN, buff=0.45)
        self.play(FadeIn(no_pixels, shift=0.15*UP), run_time=0.8)
        self.wait(1.5)

        board.hold(self, reserve=1.0)
        part1=Group(frames, video_label, mask_label, context_enc, target_enc, predictor,
                    arrow_ctx, arrow_tgt, arrow_pred, arrow_out, arrow_tgt_out,
                    pred_row, pred_label, target_row, target_label, loss_box, loss, no_pixels)
        self.play(FadeOut(part1), FadeOut(section), run_time=1.0)

        # ---------------------------------------------------------------- Part 2: planning with CEM
        board.start(self, 'planning')
        section2=label(T['section2'], font_size=30, color=MUTED)
        section2.next_to(title, RIGHT, buff=0.5).align_to(title, DOWN)
        self.play(FadeIn(section2), run_time=0.8)

        space=RoundedRectangle(width=8.2, height=5.6, corner_radius=0.2)
        space.set_stroke(PANEL_STROKE, 2).set_fill(PANEL, 1).move_to([-2.3, -0.45, 0])
        space_label=label(T['latent'], font_size=22, color=MUTED)
        space_label.next_to(space.get_corner(UL), DR, buff=0.15)

        start=np.array([-5.4, -2.3, 0.0])
        goal=np.array([0.6, 1.4, 0.0])
        start_dot=Dot(start, radius=0.12).set_fill(SKY)
        goal_dot=VGroup(Dot(goal, radius=0.1).set_fill(AMBER),
                        Circle(radius=0.22).set_stroke(AMBER, 3).move_to(goal))
        start_label=eq(r'z_t', font_size=34, color=SKY).next_to(start_dot, DOWN, buff=0.15)
        goal_label=eq(r'z_g', font_size=34, color=AMBER).next_to(goal_dot, UP, buff=0.12)

        self.play(FadeIn(space), FadeIn(space_label), run_time=0.8)
        self.play(GrowFromCenter(start_dot), FadeIn(start_label),
                  GrowFromCenter(goal_dot), FadeIn(goal_label), run_time=1.0)

        cem_title=label(T['cem_title'], font_size=26, weight='SEMIBOLD')
        cem_rows=VGroup()
        for i, (txt, tex) in enumerate(zip(T['cem'], CEM_EQS)):
            row=VGroup(label(f'{i+1}. {txt}', font_size=20, color=MUTED), eq(tex, font_size=26))
            row.arrange(DOWN, aligned_edge=LEFT, buff=0.1)
            cem_rows.add(row)
        cem_rows.arrange(DOWN, aligned_edge=LEFT, buff=0.28)
        cem_block=VGroup(cem_title, cem_rows).arrange(DOWN, aligned_edge=LEFT, buff=0.3)
        max_width=config.frame_width/2-0.35-(space.get_right()[0]+0.45)
        if cem_block.width>max_width:
            cem_block.scale_to_fit_width(max_width)
        cem_block.next_to(space, RIGHT, buff=0.45).align_to(space, UP)
        self.play(FadeIn(cem_title), LaggedStart(*[FadeIn(r) for r in cem_rows], lag_ratio=0.25), run_time=2.0)

        def rollout(actions):
            """Toy action-conditioned latent dynamics: z_{k+1} = z_k + a_k + slight swirl."""
            pts=[start.copy()]
            for a in actions:
                z=pts[-1]
                swirl=0.12*np.array([-(z[1]+0.5), z[0]+2.4, 0])/(1+np.linalg.norm(z[:2]))
                nxt=z+np.array([a[0], a[1], 0])+swirl
                nxt[:2]=np.clip(nxt[:2], space.get_corner(DL)[:2]+0.45, space.get_corner(UR)[:2]-0.45)
                pts.append(nxt)
            return np.array(pts)

        horizon, n_samples, n_elite=6, 40, 6
        mu=np.zeros((horizon, 2))
        sigma=np.full((horizon, 2), 0.7)
        iter_label=None
        for it in range(4):
            new_iter_label=label(T['iteration'].format(it+1), font_size=24, color=AMBER)
            new_iter_label.next_to(space.get_corner(DR), UL, buff=0.2)
            if iter_label is None:
                iter_label=new_iter_label
                self.play(FadeIn(iter_label), run_time=0.4)
            else:
                self.play(Transform(iter_label, new_iter_label), run_time=0.4)

            actions=mu[None]+sigma[None]*rng.standard_normal((n_samples, horizon, 2))
            paths=[rollout(a) for a in actions]
            costs=np.array([np.linalg.norm(p[-1]-goal) for p in paths])
            elite=np.argsort(costs)[:n_elite]

            curves=VGroup()
            for p in paths:
                curve=VMobject().set_points_smoothly(p)
                curve.set_stroke(SKY, 1.5, opacity=0.45)
                curves.add(curve)
            self.play(LaggedStart(*[Create(c) for c in curves], lag_ratio=0.02), run_time=1.4)
            self.play(*[curves[i].animate.set_stroke(EMERALD, 3.5, opacity=1.0) for i in elite],
                      *[c.animate.set_stroke(opacity=0.12) for j, c in enumerate(curves) if j not in elite],
                      run_time=0.7)

            mu=actions[elite].mean(axis=0)
            sigma=actions[elite].std(axis=0)+0.03
            if it<3:
                self.play(FadeOut(curves), run_time=0.5)
            else:
                best=curves[elite[0]]
                self.play(FadeOut(VGroup(*[c for j, c in enumerate(curves) if j!=elite[0]])),
                          best.animate.set_stroke(AMBER, 5), run_time=0.8)

        # MPC style: follow the best rollout, execute, replan
        plan_label=label(T['mpc'], font_size=24, color=EMERALD).next_to(space, DOWN, buff=0.2)
        self.play(FadeIn(plan_label), run_time=0.6)
        self.play(MoveAlongPath(start_dot, best), FadeOut(start_label), run_time=2.5)
        self.play(Flash(goal_dot, color=AMBER, flash_radius=0.45), run_time=0.8)
        self.wait(0.8)

        board.hold(self, reserve=1.0)
        # ---------------------------------------------------------------- Wrap-up
        board.start(self, 'summary')
        part2=Group(space, space_label, start_dot, goal_dot, goal_label, best, cem_block,
                    iter_label, plan_label, section2)
        self.play(FadeOut(part2), run_time=1.0)
        summary=VGroup(*[label(s, font_size=32, color=AMBER if i==2 else TEXT, weight='SEMIBOLD' if i==2 else 'NORMAL')
                         for i, s in enumerate(T['summary'])])
        summary.arrange(DOWN, buff=0.4)
        self.play(LaggedStart(*[FadeIn(m, shift=0.15*UP) for m in summary], lag_ratio=0.4), run_time=2.2)
        self.wait(2.5)
        board.hold(self, reserve=1.0)
        self.play(FadeOut(summary), FadeOut(title), run_time=1.0)


class JEPA2OverviewEN(JEPA2Overview):
    LANG='en'


class JEPA2OverviewES(JEPA2Overview):
    LANG='es'
