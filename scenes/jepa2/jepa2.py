"""
JEPA 2 overview animation (62 s in English, 65 s in Spanish; paced by script.yaml). Equations need LaTeX.

| File | Content |
|---|---|
| jepa2.py | Scenes and animation |
| script.yaml | Script (guion): narration and on-screen text per section and language |
| script.en.md, script.es.md | Readable script, generated by scripts/export_scripts.py |

Scenes
| Scene | Language |
|---|---|
| JEPA2OverviewEN | English |
| JEPA2OverviewES | Spanish |

Sections (self.next_section ids, same as script.yaml)
| Section | Topic | Equations |
|---|---|---|
| intro | Title | - |
| masked_prediction | V-JEPA 2 pretraining: masked tube, context and EMA encoders, predictor | L1 loss in latent space |
| planning | V-JEPA 2-AC planning with CEM toward the goal embedding | Energy, Gaussian sampling, elite refit |
| summary | Closing lines | - |

Render from the repo root (manim.cfg sets the background and ./videos output)
    python render.py -qh scenes/jepa2/jepa2.py JEPA2OverviewEN JEPA2OverviewES
One clip per section, for voice-over sync
    python render.py -qh --save_sections scenes/jepa2/jepa2.py JEPA2OverviewEN
"""
