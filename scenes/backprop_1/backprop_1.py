# Cubic fit of the Paris loss over two entries of model.layers.15.mlp.down_proj (legacy p24_28), theta in [-1, 4]
LAST_LAYER_FIT={(0, 0): 0.96407, (0, 1): -0.59912, (0, 2): 0.19671, (0, 3): -0.01644, (1, 0): -0.36597,
                (1, 1): 0.07496, (1, 2): -0.00919, (2, 0): 0.09563, (2, 1): 0.00889, (3, 0): 0.00672}
SHIFT=(-0.9, 0.05)  # alpha_shift, beta_shift of p47_wormhole: the weights start away from the trained point


# ------------------------------------------------------------------ surfaces
def last_layer_loss(t1, t2):
    return sum(c*t1**i*t2**j for (i, j), c in LAST_LAYER_FIT.items())


def hidden_valley(x, y):
    """p50_51.ipynb: wide bowl plus a narrow valley at (1, -1)."""
    return 0.2*(x**2+y**2)-np.exp(-((x-1)**2+(y+1)**2)/0.5)


def random_slice(a):
    return 11.9+0.35*np.sin(7.1*a+0.4)+0.25*np.sin(13.3*a+1.9)+0.15*np.sin(23.7*a+0.7)


def trained_slice(a):
    return 0.94+10.6*(1-np.exp(-a**2/0.9))+0.25*np.sin(9*a)*(1-np.exp(-a**2/0.3))


def moving_landscape(a, b, t):
    """Paris loss over two directions of the first 8 layers; a valley opens under SHIFT as training step t goes 0 -> 1."""
    base=1+15*(1-np.exp(-(a**2+b**2)/0.35))+0.6*np.sin(2.3*a)*np.cos(1.9*b)
    well=13.0*t*np.exp(-((a-SHIFT[0])**2+(b-SHIFT[1])**2)/(0.15+0.35*t))
    return base-well


def fit_data():
    """Same synthetic data as legacy p53.py."""
    rng=np.random.RandomState(2)
    x=rng.uniform(0, 8, 20)
    y=0.61*x+1+(rng.random_sample(20)-0.5)*2.2
    return x, y


FIT_X, FIT_Y=fit_data()


def fit_loss(m, b):
    return float(np.mean((m*FIT_X+b-FIT_Y)**2))


def descent(fn, start, lr, steps, h=1e-5):
    path=[np.array(start, dtype=float)]
    for _ in range(steps):
        x, y=path[-1]
        grad=np.array([(fn(x+h, y)-fn(x-h, y))/(2*h), (fn(x, y+h)-fn(x, y-h))/(2*h)])
        path.append(path[-1]-lr*grad)
    return path


def fit_descent(steps=1000, lr=0.01, every=40):
    """Gradient descent of p53.py from slope 0.5, intercept 2.0; one point every `every` iterations."""
    m, b=0.5, 2.0
    path=[(m, b)]
    for k in range(steps):
        err=m*FIT_X+b-FIT_Y
        m, b=m-lr*2*np.mean(err*FIT_X), b-lr*2*np.mean(err)
        if (k+1) % every == 0:
            path.append((m, b))
    return [np.array(p) for p in path]


# ------------------------------------------------------------------ drawing helpers
def ramp(t):
    """Low loss EMERALD, middle SKY, high MUTED."""
    t=min(1.0, max(0.0, t))
    return mix(EMERALD, SKY, t*2) if t < 0.5 else mix(SKY, MUTED, (t-0.5)*2)


def panel(width, height, center):
    return RoundedRectangle(width=width, height=height, corner_radius=0.25).set_fill(PANEL, 1).set_stroke(PANEL_STROKE, 2).move_to(center)


def surface_cloud(fn, x_range, y_range, center, az, z_range, n=19, scale=2.4, z_height=1.5, el=28*DEGREES, reveal=None):
    """
    Dots of z = fn(x, y) on an n x n grid, projected with azimuth `az` (a ValueTracker) and redrawn every frame,
    so fn may read other trackers. With `reveal`, only the first reveal grid points (x-major order) are drawn.
    """
    center=np.array(center, dtype=float)
    xs, ys=np.linspace(*x_range, n), np.linspace(*y_range, n)
    cells=[(x, y) for x in xs for y in ys]
    xc, yc=np.mean(x_range), np.mean(y_range)
    hx, hy=(x_range[1]-x_range[0])/2, (y_range[1]-y_range[0])/2
    z0, z1=z_range

    def project(x, y, z):
        X, Y=(x-xc)/hx*0.75, (y-yc)/hy*0.75
        Z=(min(max(z, z0), z1)-z0)/(z1-z0)*z_height
        a=az.get_value()
        xr, yr=X*np.cos(a)-Y*np.sin(a), X*np.sin(a)+Y*np.cos(a)
        return center+scale*np.array([xr, Z*np.cos(el)+yr*np.sin(el)-0.6, 0]), yr

    def build():
        shown=cells if reveal is None else cells[:int(reveal.get_value())]
        values=[(x, y, fn(x, y)) for x, y in shown]
        group=VGroup()
        for x, y, z in sorted(values, key=lambda v: -project(*v)[1]):
            pos, depth=project(x, y, z)
            group.add(Dot(pos, radius=0.045-0.01*depth, color=ramp((z-z0)/(z1-z0))))
        return group

    return always_redraw(build), project


def heatmap(fn, x_range, y_range, center, size, z_range, n=30):
    """Overhead view: n x n colored cells; to_point maps (x, y) to scene coordinates."""
    center=np.array(center, dtype=float)
    cell=size/n
    xs, ys=np.linspace(*x_range, n+1), np.linspace(*y_range, n+1)

    def to_point(x, y):
        u=(x-x_range[0])/(x_range[1]-x_range[0])-0.5
        v=(y-y_range[0])/(y_range[1]-y_range[0])-0.5
        return center+np.array([u*size, v*size, 0])

    squares=VGroup()
    for i in range(n):
        for j in range(n):
            z=fn((xs[i]+xs[i+1])/2, (ys[j]+ys[j+1])/2)
            squares.add(Square(cell).set_stroke(width=0).set_fill(ramp((z-z_range[0])/(z_range[1]-z_range[0])), 1)
                        .move_to(to_point((xs[i]+xs[i+1])/2, (ys[j]+ys[j+1])/2)))
    frame=Square(size).set_stroke(PANEL_STROKE, 2).move_to(center)
    return VGroup(squares, frame), to_point


def trail(path, progress, place, color=AMBER, z=5):
    """Dots along `path` up to `progress`, with a larger dot at the interpolated current position."""
    def position(t):
        i=min(int(t), len(path)-2)
        return path[i]+(path[i+1]-path[i])*min(1.0, t-i)

    def build():
        t=progress.get_value()
        group=VGroup(*[Dot(place(q), radius=0.045, color=color).set_z_index(z) for q in path[:int(t)+1]])
        group.add(Dot(place(position(t)), radius=0.1, color=color).set_z_index(z+1))
        return group

    return always_redraw(build), position


