        self.play(Create(rough), FadeIn(tag_rough), run_time=2.5, rate_func=linear)
        self.play(Create(smooth_curve), FadeIn(tag_smooth), run_time=3.0, rate_func=linear)
        board.hold(self, reserve=1.0)
        self.play(*[FadeOut(m) for m in (direction_eq, axes5, names5, ticks5, rough, smooth_curve, tag_rough, tag_smooth)], run_time=1.0)

        # ---------------------------------------------------------------- Part 6: a landscape that moves
        board.start(self, 'landscape')
        section6=header('landscape')
        self.play(ReplacementTransform(section5, section6), run_time=0.6)
        az=ValueTracker(20*DEGREES)
        az.add_updater(lambda m, dt: m.increment_value(0.08*dt))
        self.add(az)
        train=ValueTracker(0.0)
        box6=panel(8.6, 5.9, (-2.6, -0.45, 0))
        cloud6, project6=surface_cloud(lambda a, b: moving_landscape(a, b, train.get_value()), (-2.5, 2.5), (-2.5, 2.5),
                                       box6.get_center()+0.4*DOWN, az, (0.5, 17), n=25, scale=2.9, z_height=1.6)
        current=always_redraw(lambda: Dot(project6(*SHIFT, moving_landscape(*SHIFT, train.get_value()))[0], radius=0.12,
                                          color=AMBER).set_z_index(6))
        step_row=VGroup(label(T['step'], font_size=24, color=MUTED),
                        Integer(0, font_size=34, color=TEXT)).arrange(RIGHT, buff=0.3)
        loss6=VGroup(eq(r'L =', font_size=30, color=AMBER),
                     DecimalNumber(moving_landscape(*SHIFT, 0), num_decimal_places=2, font_size=30*EQ_SCALE, color=AMBER)).arrange(RIGHT, buff=0.15)
        legend6=VGroup(Dot(radius=0.1, color=AMBER), label(T['current'], font_size=24, color=AMBER, weight='SEMIBOLD')).arrange(RIGHT, buff=0.2)
        side6=VGroup(step_row, loss6, legend6).arrange(DOWN, aligned_edge=LEFT, buff=0.4).move_to((4.4, 0.2, 0))
        step_row[1].add_updater(lambda m: m.set_value(int(round(64*train.get_value()))))
        loss6[1].add_updater(lambda m: m.set_value(moving_landscape(*SHIFT, train.get_value())))
        self.play(FadeIn(box6), FadeIn(cloud6), FadeIn(current), FadeIn(side6), run_time=1.4)
        self.wait(1.0)
        self.play(train.animate.set_value(1.0), run_time=7.0, rate_func=smooth)
        board.hold(self, reserve=1.0)
        step_row[1].clear_updaters()
        loss6[1].clear_updaters()
        self.play(*[FadeOut(m) for m in (box6, cloud6, current, side6)], run_time=1.0)
        self.remove(az)

        # ---------------------------------------------------------------- Part 7: hidden valleys
        board.start(self, 'hidden_valley')
        section7=header('hidden_valley')
        self.play(ReplacementTransform(section6, section7), run_time=0.6)
        az=ValueTracker(-30*DEGREES)
        az.add_updater(lambda m, dt: m.increment_value(0.1*dt))
        self.add(az)
        box7=panel(6.9, 5.9, (-3.35, -0.45, 0))
        cloud7, project7=surface_cloud(hidden_valley, (-2.5, 2.5), (-2.5, 2.5), box7.get_center()+0.4*DOWN, az, (-0.65, 2.5),
                                       n=25, scale=2.6, z_height=1.5)
        box7b=panel(5.6, 5.9, (3.6, -0.45, 0))
        overhead7, to_point7=heatmap(hidden_valley, (-2.5, 2.5), (-2.5, 2.5), box7b.get_center(), 4.6, (-0.65, 1.6), n=40)
        valley_ring=Circle(radius=0.55).set_stroke(EMERALD, 3).move_to(to_point7(1, -1))
        valley_tag=label(T['valley'], font_size=24, color=EMERALD, weight='SEMIBOLD').next_to(valley_ring, DOWN, buff=0.1)
        self.play(FadeIn(box7), FadeIn(cloud7), FadeIn(box7b), FadeIn(overhead7), run_time=1.2)
        self.play(Create(valley_ring), FadeIn(valley_tag), run_time=0.8)
        path7=descent(hidden_valley, (-2.1, 2.1), lr=0.15, steps=70)[::2]
        progress7=ValueTracker(0)
        dots7a, _=trail(path7, progress7, lambda q: project7(q[0], q[1], hidden_valley(*q))[0])
        dots7b, _=trail(path7, progress7, lambda q: to_point7(*q))
        self.add(dots7a, dots7b)
        self.play(progress7.animate.set_value(len(path7)-1), run_time=6.0, rate_func=linear)
        board.hold(self, reserve=1.0)
        self.play(*[FadeOut(m) for m in (box7, cloud7, box7b, overhead7, valley_tag, valley_ring, dots7a, dots7b)], run_time=1.0)
        self.remove(az, progress7)

        # ---------------------------------------------------------------- Part 8: the same idea, small
        board.start(self, 'fit')
        section8=header('fit')
        self.play(ReplacementTransform(section7, section8), run_time=0.6)
        box8a=panel(6.6, 5.9, (-3.5, -0.45, 0))
        box8b=panel(6.6, 5.9, (3.5, -0.45, 0))
        titles8=VGroup(label(T['data_fit'], font_size=26, weight='SEMIBOLD').next_to(box8a.get_top(), DOWN, buff=0.25),
                       label(T['loss_surface'], font_size=26, weight='SEMIBOLD').next_to(box8b.get_top(), DOWN, buff=0.25))
        axes8=Axes(x_range=[0, 8, 2], y_range=[0, 7, 1], x_length=5.4, y_length=4.2, tips=False,
                   axis_config={'color': MUTED, 'stroke_width': 2}).move_to(box8a.get_center()+0.3*DOWN)
        points8=VGroup(*[Dot(axes8.c2p(x, y), radius=0.07, color=SKY) for x, y in zip(FIT_X, FIT_Y)])
        slope, intercept=ValueTracker(0.5), ValueTracker(2.0)
        line8=always_redraw(lambda: axes8.plot(lambda x: slope.get_value()*x+intercept.get_value(), x_range=[0, 8], color=AMBER,
                                               stroke_width=4))
        m_range, b_range=(0.0, 1.0), (0.0, 2.2)
        overhead8, to_point8=heatmap(fit_loss, m_range, b_range, box8b.get_center()+0.3*DOWN, 4.4, (0, 5), n=30)
        names8=VGroup(label(T['slope'], font_size=22, color=MUTED).next_to(overhead8, DOWN, buff=0.12),
                      label(T['intercept'], font_size=22, color=MUTED).rotate(PI/2).next_to(overhead8, LEFT, buff=0.12))
        self.play(FadeIn(box8a), FadeIn(box8b), FadeIn(titles8), Create(axes8), run_time=1.0)
        self.play(LaggedStart(*[GrowFromCenter(p) for p in points8], lag_ratio=0.05), FadeIn(overhead8), FadeIn(names8), run_time=1.4)
        self.add(line8)
        path8=fit_descent()
        progress8=ValueTracker(0)
        dots8, position8=trail(path8, progress8, lambda q: to_point8(*q))
        progress8.add_updater(lambda m: (slope.set_value(position8(m.get_value())[0]), intercept.set_value(position8(m.get_value())[1])))
        self.add(progress8, dots8)
        self.play(progress8.animate.set_value(len(path8)-1), run_time=5.5, rate_func=linear)
        progress8.clear_updaters()
        board.hold(self, reserve=1.0)
        self.play(*[FadeOut(m) for m in (box8a, box8b, titles8, axes8, points8, line8, overhead8, names8, dots8, section8)], run_time=1.0)
        self.remove(progress8)

        # ---------------------------------------------------------------- Wrap-up
        board.start(self, 'summary')
        summary=VGroup(*[label(line, font_size=36, color=AMBER if i == 2 else TEXT, weight='SEMIBOLD' if i == 2 else 'NORMAL')
                         for i, line in enumerate(T['summary'])]).arrange(DOWN, buff=0.45)
        if summary.width > 12.5:
            summary.scale_to_fit_width(12.5)
        self.play(LaggedStart(*[FadeIn(m, shift=0.15*UP) for m in summary], lag_ratio=0.4), run_time=2.2)
        next_part=label(T['next_part'], font_size=30, color=SKY, weight='SEMIBOLD').next_to(summary, DOWN, buff=0.8)
        self.play(FadeIn(next_part, shift=0.15*UP), run_time=0.8)
        board.hold(self, reserve=1.0)
        self.play(FadeOut(summary), FadeOut(next_part), FadeOut(title), run_time=1.0)


