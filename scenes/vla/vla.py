"""
VLA (vision-language-action) overview animation in the style of π0 (56 s in English, 61 s in Spanish; paced by script.yaml). Equations need LaTeX.

| File | Content |
|---|---|
| vla.py | Scenes and animation |
| script.yaml | Script (guion): narration and on-screen text per section and language |
| script.en.md, script.es.md | Readable script, generated by scripts/export_scripts.py |

Scenes
| Scene | Language |
|---|---|
| VLAOverviewEN | English |
| VLAOverviewES | Spanish |

Sections (self.next_section ids, same as script.yaml)
| Section | Topic | Equations |
|---|---|---|
| intro | Title | - |
| inputs | 3 cameras, instruction and robot state into the VLM (PaliGemma) and action expert | Robot state q_t |
| flow_matching | A 50-step action chunk from noise to trajectory in 10 Euler steps | Interpolation, loss, Euler update |
| execution | Chunk execution on a 2-joint arm, then replanning | Action chunk A_t |
| summary | Closing lines | - |

Render from the repo root (manim.cfg sets the background and ./videos output)
    python render.py -qh scenes/vla/vla.py VLAOverviewEN VLAOverviewES
One clip per section, for voice-over sync
    python render.py -qh --save_sections scenes/vla/vla.py VLAOverviewEN
"""
import sys
from pathlib import Path

from manim import *

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from storyboard import Storyboard  # noqa: E402
from theme import *  # noqa: E402

CAMERA_BG='#0f2d44'
TABLE='#6b5844'
PEN_BODY='#fcd34d'
JOINT_COLORS=[SKY, AMBER, PINK]
CHUNK_LEN=50


def camera_view(pen_offset, pen_angle, pen_scale=1.0):
    """Camera frame: table edge plus a pen (amber body, pink cap)."""
    frame=RoundedRectangle(width=1.8, height=1.1, corner_radius=0.08)
    frame.set_stroke(MUTED, 2).set_fill(CAMERA_BG, 1)
    table=Rectangle(width=1.8, height=0.35).set_stroke(width=0).set_fill(TABLE, 1)
    table.align_to(frame, DOWN)
    body=Rectangle(width=0.7*pen_scale, height=0.09*pen_scale).set_stroke(width=0).set_fill(PEN_BODY, 1)
    cap=Rectangle(width=0.22*pen_scale, height=0.11*pen_scale).set_stroke(width=0).set_fill(PINK, 1)
    cap.next_to(body, RIGHT, buff=0)
    pen=VGroup(body, cap).rotate(pen_angle).move_to(frame.get_center()+np.array([*pen_offset, 0]))
    return VGroup(frame, table, pen)


def token_row(colors, side=0.26, buff=0.05):
    row=VGroup(*[Square(side_length=side).set_fill(c, 1).set_stroke(PANEL, 1.5) for c in colors])
    return row.arrange(RIGHT, buff=buff)


def target_chunk():
    """Smooth reference trajectories (3 joints x CHUNK_LEN steps), values in [-1, 1]."""
    t=np.linspace(0, 1, CHUNK_LEN)
    return np.array([
        0.8*np.sin(np.pi*t)-0.1,
        -0.7*np.cos(1.4*np.pi*t)+0.1,
        0.5*np.sin(2.2*np.pi*t+0.4),
    ])


class VLAOverview(Scene):
    LANG='en'

    def construct(self):
        board=Storyboard(__file__, self.LANG)
        T=board.text
        rng=np.random.default_rng(7)

        # ---------------------------------------------------------------- Title
        board.start(self, 'intro')
        title=label('VLA', font_size=120, weight='ULTRABOLD')
        subtitle=label('Vision · Language · Action', font_size=36, color=SKY, weight='SEMIBOLD')
        subtitle.next_to(title, DOWN, buff=0.4)
        tagline=label(T['tagline'], font_size=28, color=MUTED)
        tagline.next_to(subtitle, DOWN, buff=0.3)
        self.play(Write(title), run_time=1.4)
        self.play(FadeIn(subtitle, shift=0.2*UP), FadeIn(tagline, shift=0.2*UP), run_time=1.2)
        self.wait(1.0)
        board.hold(self, reserve=1.1)
        self.play(FadeOut(subtitle), FadeOut(tagline),
                  title.animate.scale(0.38).to_corner(UL, buff=0.35), run_time=1.1)

        # ---------------------------------------------------------------- Part 1: inputs and tokens
        board.start(self, 'inputs')
        section=label(T['section1'], font_size=30, color=MUTED)
        section.next_to(title, RIGHT, buff=0.5).align_to(title, DOWN)
        self.play(FadeIn(section), run_time=0.6)

        cams=VGroup(
            camera_view((0.0, -0.15), 0.25, 0.9),
            camera_view((-0.3, -0.05), -0.5, 1.4),
            camera_view((0.25, -0.1), 0.9, 1.2),
        ).arrange(DOWN, buff=0.28).move_to([-5.3, 0.9, 0]).to_edge(LEFT, buff=0.6)
        cam_labels=VGroup(*[label(n, font_size=13, color=TEXT, weight='MEDIUM')
                            .next_to(c[0].get_corner(UL), DR, buff=0.07)
                            for n, c in zip(T['cams'], cams)])

        prompt=label('"uncap the pen"', font_size=24, weight='MEDIUM').move_to([-5.3, -2.0, 0]).align_to(cams, LEFT)
        state=eq(r'q_t = [\,0.1,\ -0.4,\ 0.7,\ \dots\,]', font_size=24, color=EMERALD)
        state.move_to([-5.3, -2.9, 0]).align_to(cams, LEFT)

        self.play(LaggedStart(*[FadeIn(c, shift=0.2*RIGHT) for c in cams], lag_ratio=0.25),
                  FadeIn(cam_labels), run_time=1.6)
        self.play(Write(prompt), run_time=1.0)
        self.play(FadeIn(state, shift=0.15*UP), run_time=0.7)

        siglip=card('SigLIP', width=1.6, height=0.8, color=SKY, font_size=24).move_to([-3.0, 0.9, 0])
        tokenizer=card('Tokenizer', width=1.7, height=0.7, color=SAND, font_size=22).move_to([-2.7, -2.0, 0])
        cam_arrows=VGroup(*[Arrow(c.get_right(), siglip.get_left(), buff=0.1, stroke_width=3).set_color(TEXT)
                            for c in cams])
        prompt_arrow=Arrow(prompt.get_right(), tokenizer.get_left(), buff=0.1, stroke_width=3).set_color(TEXT)
        self.play(FadeIn(siglip), LaggedStart(*[GrowArrow(a) for a in cam_arrows], lag_ratio=0.2),
                  FadeIn(tokenizer), GrowArrow(prompt_arrow), run_time=1.3)

        # Token sequence: 3 cameras x 4 image tokens, 3 text tokens, 1 state token
        img_tokens=VGroup(*[token_row([mix(CAMERA_BG, SKY, v) for v in rng.uniform(0.35, 1, 4)])
                            for _ in range(3)])
        img_tokens.arrange(RIGHT, buff=0.14)
        txt_tokens=VGroup()
        for w in ['uncap', 'the', 'pen']:
            t=label(w, font_size=18, color=PANEL, weight='SEMIBOLD')
            bg=RoundedRectangle(width=t.get_width()+0.18, height=0.34, corner_radius=0.06)
            bg.set_fill(SAND, 1).set_stroke(width=0)
            txt_tokens.add(VGroup(bg, t.move_to(bg)))
        txt_tokens.arrange(RIGHT, buff=0.05)
        state_token=token_row([EMERALD])
        sequence=VGroup(img_tokens, txt_tokens, state_token).arrange(RIGHT, buff=0.22)
        sequence.move_to([2.3, -0.55, 0])
        seq_label=label(T['sequence'], font_size=20, color=MUTED).next_to(sequence, DOWN, buff=0.15)

        self.play(TransformFromCopy(siglip, img_tokens),
                  TransformFromCopy(tokenizer, txt_tokens),
                  TransformFromCopy(state, state_token), run_time=1.6)
        self.play(FadeIn(seq_label), run_time=0.5)

        vlm=card('VLM (PaliGemma 3B)', width=5.6, height=1.0, color=SKY, font_size=26).move_to([2.3, 1.15, 0])
        expert=card('Action expert (300M)', width=4.0, height=0.85, color=AMBER, font_size=24).move_to([2.3, -2.4, 0])
        up_arrow=Arrow(sequence.get_top(), vlm.get_bottom(), buff=0.1).set_color(TEXT)
        attn_lines=VGroup(*[
            DashedLine(vlm.get_bottom()+np.array([x, 0, 0]), expert.get_top()+np.array([0.6*x, 0, 0]))
            .set_stroke(AMBER, 1.5, opacity=0.6)
            for x in np.linspace(-2.4, 2.4, 7)
        ])
        attn_label=label(T['attends'], font_size=18, color=AMBER).next_to(expert, DOWN, buff=0.15)

        self.play(GrowArrow(up_arrow), FadeIn(vlm), run_time=1.0)
        self.play(FadeIn(expert),
                  LaggedStart(*[Create(l) for l in attn_lines], lag_ratio=0.08),
                  FadeIn(attn_label), run_time=1.5)
        self.wait(1.2)

        board.hold(self, reserve=0.9)
        part1_inputs=Group(cams, cam_labels, prompt, state, siglip, tokenizer, cam_arrows, prompt_arrow,
                           sequence, seq_label, up_arrow, attn_lines, attn_label)
        self.play(FadeOut(part1_inputs), FadeOut(section), run_time=0.9)

        # ---------------------------------------------------------------- Part 2: flow matching
        board.start(self, 'flow_matching')
        section2=label(T['section2'], font_size=30, color=MUTED)
        section2.next_to(title, RIGHT, buff=0.5).align_to(title, DOWN)
        self.play(FadeIn(section2),
                  vlm.animate.scale(0.6).move_to([-4.6, 2.2, 0]),
                  expert.animate.move_to([-4.6, 0.9, 0]), run_time=1.2)
        ctx_arrow=Arrow(vlm.get_bottom(), expert.get_top(), buff=0.08).set_color(TEXT)
        ctx_label=label(T['context'], font_size=18, color=MUTED).next_to(ctx_arrow, RIGHT, buff=0.1)
        self.play(GrowArrow(ctx_arrow), FadeIn(ctx_label), run_time=0.7)

        plot_w, plot_h=5.8, 3.6
        plot_origin=np.array([0.6, -2.0, 0])
        plot_box=Rectangle(width=plot_w, height=plot_h).set_stroke(PANEL_STROKE, 2).set_fill(PANEL, 1)
        plot_box.move_to(plot_origin+np.array([plot_w/2, plot_h/2, 0]))
        x_label=VGroup(label(T['x_axis'], font_size=20, color=MUTED), eq(r'(H = 50)', font_size=26, color=MUTED))
        x_label.arrange(RIGHT, buff=0.12).next_to(plot_box, DOWN, buff=0.15)
        y_label=label(T['y_axis'], font_size=20, color=MUTED).rotate(PI/2)
        y_label.next_to(plot_box, LEFT, buff=0.15)

        def to_plot(values):
            xs=plot_origin[0]+np.linspace(0.15, plot_w-0.15, CHUNK_LEN)
            ys=plot_origin[1]+plot_h/2+values*(plot_h/2-0.2)
            return np.stack([xs, ys, np.zeros_like(xs)], axis=1)

        def chunk_curves(chunk):
            return VGroup(*[VMobject().set_points_as_corners(to_plot(np.clip(row, -1, 1)))
                            .set_stroke(c, 3) for row, c in zip(chunk, JOINT_COLORS)])

        noise=rng.standard_normal((3, CHUNK_LEN))*0.55
        target=target_chunk()
        curves=chunk_curves(noise)
        out_arrow=Arrow(expert.get_right(), y_label.get_left()+0.5*UP, buff=0.12).set_color(TEXT)

        self.play(FadeIn(plot_box), FadeIn(x_label), FadeIn(y_label), GrowArrow(out_arrow), run_time=1.0)

        def tau_caption(step):
            tag=T['chunk'] if step==10 else (T['noise'] if step==0 else '')
            color=EMERALD if step==10 else TEXT
            group=VGroup(eq(rf'\tau = {step/10:.1f}', font_size=34, color=color))
            if tag:
                group.add(label(tag, font_size=24, color=color))
            return group.arrange(RIGHT, buff=0.25).next_to(plot_box, UP, buff=0.2)

        tau_text=tau_caption(0)
        self.play(Create(curves), FadeIn(tau_text), run_time=1.0)

        equations=VGroup(
            label(T['train'], font_size=20, color=MUTED, weight='SEMIBOLD'),
            eq(r'A_t^{\tau} = \tau A_t + (1-\tau)\,\epsilon', font_size=30),
            eq(r'\mathcal{L} = \lVert v_{\theta}(A_t^{\tau}, o_t) - (A_t - \epsilon) \rVert^{2}', font_size=30),
            label(T['infer'], font_size=20, color=MUTED, weight='SEMIBOLD'),
            eq(r'A_t^{\tau+\delta} = A_t^{\tau} + \delta\, v_{\theta}(A_t^{\tau}, o_t)', font_size=30, color=AMBER),
        )
        equations.arrange(DOWN, aligned_edge=LEFT, buff=0.16)
        equations[3].shift(0.12*DOWN)
        equations[4].shift(0.12*DOWN)
        equations.move_to([-4.3, -1.75, 0]).to_edge(LEFT, buff=0.55)
        self.play(LaggedStart(*[FadeIn(m) for m in equations], lag_ratio=0.25), run_time=1.6)

        for step in range(1, 11):
            tau=step/10
            chunk=(1-tau)*noise+tau*target
            self.play(Transform(curves, chunk_curves(chunk)), Transform(tau_text, tau_caption(step)),
                      run_time=0.45, rate_func=linear)
        self.wait(1.0)

        board.hold(self, reserve=0.9)
        # ---------------------------------------------------------------- Part 3: execution
        board.start(self, 'execution')
        section3=label(T['section3'], font_size=30, color=MUTED)
        section3.next_to(title, RIGHT, buff=0.5).align_to(title, DOWN)
        self.play(FadeOut(Group(vlm, expert, ctx_arrow, ctx_label, out_arrow, equations)),
                  Transform(section2, section3), run_time=0.9)

        chunk_eq=eq(r'A_t = [\,a_t,\ a_{t+1},\ \dots,\ a_{t+49}\,]', font_size=32, color=EMERALD)
        chunk_eq.move_to([-3.7, 2.3, 0])

        base=np.array([-4.3, -2.6, 0])
        table=Line([-6.8, -2.6, 0], [-0.6, -2.6, 0]).set_stroke(MUTED, 4)
        l1, l2=2.1, 1.7

        def joint_angles(i):
            """Map chunk step i to the 2 link angles (joints 0 and 1 of the chunk)."""
            return PI/2-0.9*target[0][i], -1.1-0.8*target[1][i]

        def arm_points(i):
            a1, a2=joint_angles(i)
            elbow=base+l1*np.array([np.cos(a1), np.sin(a1), 0])
            hand=elbow+l2*np.array([np.cos(a1+a2), np.sin(a1+a2), 0])
            return elbow, hand

        elbow0, hand0=arm_points(0)
        upper=Line(base, elbow0).set_stroke(SAND, 10)
        fore=Line(elbow0, hand0).set_stroke(SAND, 8)
        joints=VGroup(Dot(base, radius=0.13), Dot(elbow0, radius=0.11), Dot(hand0, radius=0.09))
        for d, c in zip(joints, JOINT_COLORS):
            d.set_fill(c).set_stroke(PANEL, 2)
        trace=TracedPath(joints[2].get_center, stroke_color=EMERALD, stroke_width=3)

        _, hand_end=arm_points(CHUNK_LEN-1)
        pen=VGroup(Rectangle(width=0.55, height=0.09).set_fill(PEN_BODY, 1).set_stroke(width=0),
                   Rectangle(width=0.18, height=0.11).set_fill(PINK, 1).set_stroke(width=0))
        pen[1].next_to(pen[0], RIGHT, buff=0)
        pen.move_to(hand_end+np.array([-0.2, 0, 0]))

        self.play(Create(table), FadeIn(VGroup(upper, fore, joints)), FadeIn(pen), Write(chunk_eq),
                  run_time=1.2)
        self.add(trace)

        cursor=Line(plot_box.get_bottom(), plot_box.get_top()).set_stroke(EMERALD, 2)
        cursor.move_to(to_plot(np.zeros(CHUNK_LEN))[0]).match_y(plot_box)
        self.play(FadeIn(cursor), run_time=0.3)

        def update_arm(mob, alpha):
            i=int(round(alpha*(CHUNK_LEN-1)))
            elbow, hand=arm_points(i)
            upper.put_start_and_end_on(base, elbow)
            fore.put_start_and_end_on(elbow, hand)
            joints[1].move_to(elbow)
            joints[2].move_to(hand)
            cursor.match_x(Dot(to_plot(np.zeros(CHUNK_LEN))[i]))
            return mob

        self.play(UpdateFromAlphaFunc(VGroup(upper, fore, joints, cursor), update_arm),
                  run_time=4.0, rate_func=linear)
        self.play(pen[1].animate.shift(0.45*RIGHT+0.2*UP).rotate(0.6), run_time=0.8)
        self.wait(0.4)

        replan=label(T['replan'], font_size=22, color=EMERALD).to_edge(DOWN, buff=0.25)
        self.play(FadeIn(replan, shift=0.1*UP), run_time=0.7)
        self.wait(1.5)

        board.hold(self, reserve=1.0)
        # ---------------------------------------------------------------- Wrap-up
        board.start(self, 'summary')
        self.remove(trace)
        everything=Group(table, upper, fore, joints, pen, cursor, plot_box, curves, tau_text, x_label, y_label,
                         replan, section2, chunk_eq)
        self.play(FadeOut(everything), run_time=1.0)
        summary=VGroup(*[label(s, font_size=32, color=AMBER if i==2 else TEXT, weight='SEMIBOLD' if i==2 else 'NORMAL')
                         for i, s in enumerate(T['summary'])])
        summary.arrange(DOWN, buff=0.4)
        self.play(LaggedStart(*[FadeIn(m, shift=0.15*UP) for m in summary], lag_ratio=0.4), run_time=2.2)
        self.wait(2.5)
        board.hold(self, reserve=1.0)
        self.play(FadeOut(summary), FadeOut(title), run_time=1.0)


class VLAOverviewEN(VLAOverview):
    LANG='en'


class VLAOverviewES(VLAOverview):
    LANG='es'
