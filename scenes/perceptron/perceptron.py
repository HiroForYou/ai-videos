# ------------------------------------------------------------------ geometry helpers
def clip_polygon(points, a, b, c):
    """Keep the part of a convex polygon where a*x + b*y + c >= 0 (Sutherland-Hodgman, one edge)."""
    out=[]
    for i, p in enumerate(points):
        q=points[(i+1) % len(points)]
        fp=a*p[0]+b*p[1]+c
        fq=a*q[0]+b*q[1]+c
        if fp >= 0:
            out.append(p)
        if (fp >= 0) != (fq >= 0):
            t=fp/(fp-fq)
            out.append((p[0]+t*(q[0]-p[0]), p[1]+t*(q[1]-p[1])))
    return out


def square(L=PLOT_RANGE):
    return [(-L, -L), (L, -L), (L, L), (-L, L)]


def line_in_square(a, b, c, L=PLOT_RANGE):
    """Endpoints of a*x + b*y + c = 0 inside [-L, L]^2, or None."""
    pts=[]
    for x in (-L, L):
        if abs(b) > 1e-9:
            y=-(a*x+c)/b
            if -L <= y <= L:
                pts.append((x, y))
    for y in (-L, L):
        if abs(a) > 1e-9:
            x=-(b*y+c)/a
            if -L <= x <= L:
                pts.append((x, y))
    return (pts[0], pts[-1]) if len(pts) >= 2 else None


class PlotPanel(VGroup):
    """Square panel with axes; to_point maps data coordinates in [-L, L]^2 to scene coordinates."""

    def __init__(self, center, size=5.0, **kwargs):
        super().__init__(**kwargs)
        self.center_point=np.array([*center, 0][:3], dtype=float)
        self.size=size
        frame=RoundedRectangle(width=size, height=size, corner_radius=0.2).set_fill(PANEL, 1).set_stroke(PANEL_STROKE, 2)
        frame.move_to(self.center_point)
        axes=VGroup(Line(self.to_point((-PLOT_RANGE, 0)), self.to_point((PLOT_RANGE, 0))),
                    Line(self.to_point((0, -PLOT_RANGE)), self.to_point((0, PLOT_RANGE)))).set_stroke(PANEL_STROKE, 3)
        self.add(frame, axes)

    def to_point(self, p):
        return self.center_point+np.array([p[0], p[1], 0])*(self.size/2)/PLOT_RANGE


def data_dot(point, label):
    color=AMBER if label > 0 else SKY
    dot=Dot(point, radius=0.2, color=color)
    sign=MathTex('+' if label > 0 else '-', font_size=40, color=PANEL).move_to(point)
    return VGroup(dot, sign)


def dial(name, tracker, center, color=AMBER, radius=0.55, vmin=-2.0, vmax=2.0):
    """Knob with ticks from vmin to vmax and a needle that follows `tracker` (legacy P45 dials)."""
    center=np.array(center, dtype=float)

    def direction(v):
        angle=PI/2-(v-vmin)/(vmax-vmin)*(1.5*PI)+0.75*PI
        return np.array([np.cos(angle), np.sin(angle), 0])

    face=Circle(radius=radius).set_fill(PANEL, 1).set_stroke(PANEL_STROKE, 3).move_to(center)
    ticks=VGroup()
    for i in range(17):
        v=vmin+i*(vmax-vmin)/16
        major=i % 4 == 0
        ticks.add(Line(center+direction(v)*radius*(0.72 if major else 0.84), center+direction(v)*radius*0.96)
                  .set_stroke(SAND if major else MUTED, 3 if major else 1.5))
    # The needle follows the face, so the whole dial can be moved or scaled
    needle=always_redraw(lambda: Line(face.get_center(), face.get_center()+direction(tracker.get_value())*face.width/2*0.7)
                         .set_stroke(color, 6))
    hub=Dot(center, radius=0.06, color=color)
    name_tex=eq(name+' =', font_size=22, color=color)
    value=DecimalNumber(tracker.get_value(), num_decimal_places=2, include_sign=False, font_size=22*EQ_SCALE, color=color)
    value.add_updater(lambda m: m.set_value(tracker.get_value()))
    readout=VGroup(name_tex, value).arrange(RIGHT, buff=0.12).next_to(face, DOWN, buff=0.18)
    value.add_updater(lambda m: m.next_to(name_tex, RIGHT, buff=0.12))
    return VGroup(face, ticks, needle, hub, readout)


def projected_cloud(fn, w_range, center, az, n=13, scale=2.0, e_max=20.0, z_height=1.5, el=28*DEGREES, offset=(0.5, 0.5),
                    colors=(EMERALD, SKY, MUTED), reveal=None):
    """
    Dots of z = fn(w0, w1) on an n x n grid, projected with azimuth `az` (a ValueTracker); redrawn every frame.
    fn is evaluated on every redraw, so it may read other trackers (e.g. the bias). With `reveal` (a ValueTracker),
    only the first reveal grid points (w0-major order) are drawn.
    """
    center=np.array(center, dtype=float)
    grid=np.linspace(w_range[0], w_range[1], n)
    span=(w_range[1]-w_range[0])/2
    cells=[(w0, w1) for w0 in grid for w1 in grid]

    def project(w0, w1, e):
        X=(w0-offset[0])/span*0.75
        Y=(w1-offset[1])/span*0.75
        Z=min(e, e_max)/e_max*z_height
        a=az.get_value()
        xr=X*np.cos(a)-Y*np.sin(a)
        yr=X*np.sin(a)+Y*np.cos(a)
        return center+scale*np.array([xr, Z*np.cos(el)+yr*np.sin(el)-0.6, 0]), yr

    def color_of(e):
        t=min(1.0, e/(0.7*e_max))
        return mix(colors[0], colors[1], t*2) if t < 0.5 else mix(colors[1], colors[2], (t-0.5)*2)

    def build():
        shown=cells if reveal is None else cells[:int(reveal.get_value())]
        values=[(w0, w1, fn(w0, w1)) for w0, w1 in shown]
        group=VGroup()
        for w0, w1, e in sorted(values, key=lambda v: -project(*v)[1]):
            pos, depth=project(w0, w1, e)
            group.add(Dot(pos, radius=0.045-0.01*depth, color=color_of(e)))
        return group

    return always_redraw(build), project


def or_error(w0, w1, b=1.0):
    """Squared error of the weighted sum over the four OR points (bias fixed)."""
    return sum((y-(w0*x0+w1*x1+b))**2 for (x0, x1), y in OR_DATA)


def two_layer_error(w00, w01, activation):
    """Mean squared error of the legacy 2-2-1 XOR network (p66_67 NeuralNetworkTwoParam), labels in {0, 1}."""
    total=0.0
    for (x0, x1), label in XOR_DATA:
        y=1.0 if label > 0 else 0.0
        h0=activation(x0*w00+x1*1.0+0.5)
        h1=activation(x0*w01+x1*1.0-1.5)
        out=activation(h0*1.0+h1*(-1.0)-0.4)
        total+=(y-out)**2
    return total/len(XOR_DATA)


def step(z):
    return 1.0 if z >= 0 else 0.0


def sigmoid(z):
    return 1.0/(1.0+np.exp(-z))


